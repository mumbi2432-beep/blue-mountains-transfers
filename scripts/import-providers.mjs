#!/usr/bin/env node
// Turn a CSV of providers (from public registers or your own research) into SQL for D1.
//
//   node scripts/import-providers.mjs providers.csv > import.sql
//   npx wrangler d1 execute nepali-property-market --remote --file=import.sql
//
// Columns (header row required; extra columns ignored):
//   name, business_name, category, licence_no, abn, phone, email, website, suburb, state,
//   areas (area slugs separated by ";", e.g. "schofields-nsw;blacktown-lga-nsw" or "city:sydney"),
//   nepali_speaking (0/1, ONLY if confirmed), licence_verified (0/1, ONLY if checked), source, description
//
// Rows are imported as status=unclaimed, plan=free. Existing slugs are skipped (safe to re-run).
import { readFileSync } from "node:fs";

const file = process.argv[2];
if (!file) { console.error("usage: node scripts/import-providers.mjs providers.csv > import.sql"); process.exit(1); }

function parseCsv(text) {
	const rows = []; let row = [], cur = "", q = false;
	for (let i = 0; i < text.length; i++) {
		const c = text[i];
		if (q) { if (c === '"' && text[i + 1] === '"') { cur += '"'; i++; } else if (c === '"') q = false; else cur += c; }
		else if (c === '"') q = true;
		else if (c === ",") { row.push(cur); cur = ""; }
		else if (c === "\n" || c === "\r") { if (c === "\r" && text[i + 1] === "\n") i++; row.push(cur); cur = ""; if (row.some((x) => x.trim())) rows.push(row); row = []; }
		else cur += c;
	}
	if (cur || row.length) { row.push(cur); if (row.some((x) => x.trim())) rows.push(row); }
	return rows;
}
const slugify = (s) => s.toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 80);
const esc = (v) => (v === undefined || v === null || String(v).trim() === "" ? "NULL" : `'${String(v).trim().replace(/'/g, "''")}'`);
const CATEGORIES = ["nepalese-real-estate-agents","nepalese-mortgage-brokers","nepalese-conveyancers","nepalese-accountants","nepalese-buyers-agents","nepalese-building-pest-inspectors"];

const [header, ...data] = parseCsv(readFileSync(file, "utf8"));
const col = Object.fromEntries(header.map((h, i) => [h.trim().toLowerCase(), i]));
for (const need of ["name", "category"]) if (!(need in col)) { console.error(`missing column: ${need}`); process.exit(1); }
const get = (r, k) => (k in col ? (r[col[k]] ?? "").trim() : "");

const seen = new Set(); let n = 0;
console.log("-- generated by scripts/import-providers.mjs");
for (const r of data) {
	const category = get(r, "category");
	if (!CATEGORIES.includes(category)) { console.error(`skip (bad category "${category}"): ${get(r, "name")}`); continue; }
	const name = get(r, "name");
	let slug = slugify(`${get(r, "business_name") || name}-${get(r, "suburb")}`);
	if (seen.has(slug)) slug += `-${seen.size}`;
	seen.add(slug);
	console.log(
		`INSERT OR IGNORE INTO providers (slug,name,category,business_name,licence_no,abn,description,phone,email,website,address_suburb,address_state,nepali_speaking,licence_verified,status,plan,source) VALUES (` +
		[esc(slug), esc(name), esc(category), esc(get(r, "business_name")), esc(get(r, "licence_no")), esc(get(r, "abn")), esc(get(r, "description")),
		 esc(get(r, "phone")), esc(get(r, "email")), esc(get(r, "website")), esc(get(r, "suburb")), esc(get(r, "state")),
		 get(r, "nepali_speaking") === "1" ? 1 : 0, get(r, "licence_verified") === "1" ? 1 : 0, "'unclaimed'", "'free'", esc(get(r, "source"))].join(",") + `);`,
	);
	for (const a of get(r, "areas").split(";").map((x) => x.trim()).filter(Boolean)) {
		console.log(`INSERT OR IGNORE INTO provider_areas (provider_id, area_slug, is_top) SELECT id, ${esc(a)}, 0 FROM providers WHERE slug = ${esc(slug)};`);
	}
	n++;
}
console.error(`generated ${n} providers`);
